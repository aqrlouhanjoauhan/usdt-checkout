let currentLang = "en";

function t(key) {
    if (I18N_RESOURCES[currentLang] && I18N_RESOURCES[currentLang][key] !== undefined) {
        return I18N_RESOURCES[currentLang][key];
    }
    if (I18N_RESOURCES["en"] && I18N_RESOURCES["en"][key] !== undefined) {
        return I18N_RESOURCES["en"][key];
    }
    return key;
}

function getCodeText(code, fallbackKey = "toast_network_error") {
    if (!code) return t(fallbackKey);
    return t(code) || t(fallbackKey);
}

function localizeProjectName(rawProject) {
    if (!rawProject || rawProject === "__CUSTOM_MODE_ORDER__") return t("default_project_name");
    if (rawProject === "__UNNAMED_PROJECT__") return t("TAG_UNNAMED_PROJECT");
    if (rawProject === "__PARSE_ERROR__") return t("TAG_PARSE_ERROR");
    if (rawProject === "__FIXED_ORDER__") return t("TAG_FIXED_ORDER");
    return rawProject;
}

function updatePageTexts() {
    document.title = t("page_title");
    document.documentElement.lang = currentLang;

    if (currentLang === "ar") {
        document.documentElement.dir = "rtl";
    } else {
        document.documentElement.dir = "ltr";
    }

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key.endsWith("_html")) {
            el.innerHTML = t(key);
        } else {
            el.innerText = t(key);
        }
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(el => {
        const rules = el.getAttribute("data-i18n-attr").split(";");
        rules.forEach(rule => {
            const [attr, key] = rule.split(":").map(s => s.trim());
            if (attr && key) {
                el.setAttribute(attr, t(key));
            }
        });
    });

    const addrEl = document.getElementById("target-address");
    if (addrEl) {
        const currentText = addrEl.innerText.trim();
        if (!currentText || currentText.includes("...") || currentText.includes("加载") || currentText.includes("Loading")) {
            addrEl.innerText = t("loading_text");
        }
    }

    const productTitleEl = document.getElementById("product-title-text");
    if (productTitleEl) {
        const rawCode = productTitleEl.getAttribute("data-raw-project");
        if (rawCode) {
            productTitleEl.innerText = localizeProjectName(rawCode);
        }
    }

    const langSelect = document.getElementById("lang-select");
    if (langSelect && langSelect.value !== currentLang) {
        langSelect.value = currentLang;
    }
}

function changeLanguage(lang) {
    if (!I18N_RESOURCES[lang]) return;
    currentLang = lang;
    localStorage.setItem("app_lang", lang);
    updatePageTexts();
}

function initI18n() {
    const saved = localStorage.getItem("app_lang");
    if (saved && I18N_RESOURCES[saved]) {
        currentLang = saved;
    } else {
        const rawLang = (navigator.language || (navigator.languages && navigator.languages[0]) || "").toLowerCase();
        
        if (I18N_RESOURCES[rawLang]) {
            currentLang = rawLang;
        } else if (rawLang.startsWith("zh")) {
            if (rawLang.includes("tw") || rawLang.includes("hk") || rawLang.includes("mo") || rawLang.includes("hant")) {
                currentLang = "zh-TW";
            } else {
                currentLang = "zh-CN";
            }
        } else {
            const prefix = rawLang.split("-")[0];
            if (I18N_RESOURCES[prefix]) {
                currentLang = prefix;
            } else {
                currentLang = "en";
            }
        }
    }
    updatePageTexts();
}

document.addEventListener("DOMContentLoaded", initI18n);
